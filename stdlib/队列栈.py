"""
段言标准库 - 队列栈模块

提供栈、队列、双端队列数据结构操作。
"""

from collections import deque
from typing import Any, List, Optional


# =============================================================================
# 栈操作
# =============================================================================

def 创建栈() -> list:
    """创建空栈"""
    return []


def 入栈(栈: list, 值: Any) -> None:
    """
    将值压入栈顶

    参数:
        栈: 栈列表
        值: 要压入的值
    """
    栈.append(值)


def 出栈(栈: list) -> Any:
    """
    弹出栈顶元素

    参数:
        栈: 栈列表

    返回:
        栈顶元素

    异常:
        RuntimeError: 栈为空时
    """
    if not 栈:
        raise RuntimeError("栈为空，无法出栈")
    return 栈.pop()


def 查看栈顶(栈: list) -> Any:
    """
    查看栈顶元素（不弹出）

    参数:
        栈: 栈列表

    返回:
        栈顶元素

    异常:
        RuntimeError: 栈为空时
    """
    if not 栈:
        raise RuntimeError("栈为空，无法查看栈顶")
    return 栈[-1]


def 栈是否为空(栈: list) -> bool:
    """
    判断栈是否为空

    参数:
        栈: 栈列表

    返回:
        True 如果栈为空
    """
    return len(栈) == 0


def 栈大小(栈: list) -> int:
    """
    获取栈中元素数量

    参数:
        栈: 栈列表

    返回:
        栈中元素数量
    """
    return len(栈)


# =============================================================================
# 队列操作
# =============================================================================

def 创建队列() -> deque:
    """创建空队列"""
    return deque()


def 入队(队列: deque, 值: Any) -> None:
    """
    将值加入队尾

    参数:
        队列: 队列
        值: 要加入的值
    """
    队列.append(值)


def 出队(队列: deque) -> Any:
    """
    从队首取出元素

    参数:
        队列: 队列

    返回:
        队首元素

    异常:
        RuntimeError: 队列为空时
    """
    if not 队列:
        raise RuntimeError("队列为空，无法出队")
    return 队列.popleft()


def 查看队首(队列: deque) -> Any:
    """
    查看队首元素（不取出）

    参数:
        队列: 队列

    返回:
        队首元素

    异常:
        RuntimeError: 队列为空时
    """
    if not 队列:
        raise RuntimeError("队列为空，无法查看队首")
    return 队列[0]


def 队列是否为空(队列: deque) -> bool:
    """
    判断队列是否为空

    参数:
        队列: 队列

    返回:
        True 如果队列为空
    """
    return len(队列) == 0


def 队列大小(队列: deque) -> int:
    """
    获取队列中元素数量

    参数:
        队列: 队列

    返回:
        队列中元素数量
    """
    return len(队列)


# =============================================================================
# 双端队列操作
# =============================================================================

def 创建双端队列() -> deque:
    """创建空双端队列"""
    return deque()


def 左入(双端队列: deque, 值: Any) -> None:
    """
    从左端插入值

    参数:
        双端队列: 双端队列
        值: 要插入的值
    """
    双端队列.appendleft(值)


def 右入(双端队列: deque, 值: Any) -> None:
    """
    从右端插入值

    参数:
        双端队列: 双端队列
        值: 要插入的值
    """
    双端队列.append(值)


def 左出(双端队列: deque) -> Any:
    """
    从左端取出元素

    参数:
        双端队列: 双端队列

    返回:
        左端元素

    异常:
        RuntimeError: 双端队列为空时
    """
    if not 双端队列:
        raise RuntimeError("双端队列为空，无法左出")
    return 双端队列.popleft()


def 右出(双端队列: deque) -> Any:
    """
    从右端取出元素

    参数:
        双端队列: 双端队列

    返回:
        右端元素

    异常:
        RuntimeError: 双端队列为空时
    """
    if not 双端队列:
        raise RuntimeError("双端队列为空，无法右出")
    return 双端队列.pop()


def 查看左端(双端队列: deque) -> Any:
    """
    查看左端元素（不取出）

    参数:
        双端队列: 双端队列

    返回:
        左端元素

    异常:
        RuntimeError: 双端队列为空时
    """
    if not 双端队列:
        raise RuntimeError("双端队列为空，无法查看左端")
    return 双端队列[0]


def 查看右端(双端队列: deque) -> Any:
    """
    查看右端元素（不取出）

    参数:
        双端队列: 双端队列

    返回:
        右端元素

    异常:
        RuntimeError: 双端队列为空时
    """
    if not 双端队列:
        raise RuntimeError("双端队列为空，无法查看右端")
    return 双端队列[-1]


def 双端队列是否为空(双端队列: deque) -> bool:
    """
    判断双端队列是否为空

    参数:
        双端队列: 双端队列

    返回:
        True 如果双端队列为空
    """
    return len(双端队列) == 0


def 双端队列大小(双端队列: deque) -> int:
    """
    获取双端队列中元素数量

    参数:
        双端队列: 双端队列

    返回:
        双端队列中元素数量
    """
    return len(双端队列)


