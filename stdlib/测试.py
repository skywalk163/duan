"""
段言标准库 - 测试模块

提供简单测试框架：断言、测试套件管理。
"""

from typing import Any, Callable, Optional
import math

# 内部状态
_通过数 = 0
_失败数 = 0
_当前套件名 = ""
_失败列表 = []


def 断言相等(实际: Any, 期望: Any, 消息: str = "") -> None:
    """
    断言实际值等于期望值

    参数:
        实际: 实际值
        期望: 期望值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if 实际 == 期望:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望 {期望!r}，实际 {实际!r}")


def 断言不等(实际: Any, 期望: Any, 消息: str = "") -> None:
    """
    断言实际值不等于期望值

    参数:
        实际: 实际值
        期望: 不期望的值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if 实际 != 期望:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望不等于 {期望!r}，但实际相等")


def 断言为真(值: Any, 消息: str = "") -> None:
    """
    断言值为真

    参数:
        值: 要判断的值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if 值:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望为真，实际为 {值!r}")


def 断言为假(值: Any, 消息: str = "") -> None:
    """
    断言值为假

    参数:
        值: 要判断的值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if not 值:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望为假，实际为 {值!r}")


def 断言为空(值: Any, 消息: str = "") -> None:
    """
    断言值为空（None、空字符串、空列表、空字典等）

    参数:
        值: 要判断的值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if not 值 and 值 != 0 and 值 is not False:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望为空，实际为 {值!r}")


def 断言不为空(值: Any, 消息: str = "") -> None:
    """
    断言值不为空

    参数:
        值: 要判断的值
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if 值 or 值 == 0 or 值 is False:
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望不为空，实际为 {值!r}")


def 断言近似(实际: float, 期望: float, 精度: float = 1e-9, 消息: str = "") -> None:
    """
    断言浮点数近似相等

    参数:
        实际: 实际值
        期望: 期望值
        精度: 允许的误差范围（默认 1e-9）
        消息: 可选的附加消息
    """
    global _通过数, _失败数
    if math.isclose(实际, 期望, abs_tol=精度):
        _通过数 += 1
    else:
        _失败数 += 1
        前缀 = f"{消息}: " if 消息 else ""
        _失败列表.append(f"{前缀}期望 {期望}（精度±{精度}），实际 {实际}")


def 测试开始(名称: str) -> None:
    """
    开始一个测试套件

    参数:
        名称: 测试套件名称
    """
    global _通过数, _失败数, _当前套件名, _失败列表
    _通过数 = 0
    _失败数 = 0
    _当前套件名 = 名称
    _失败列表 = []
    print(f"▶ 开始测试：{名称}")


def 测试结束() -> None:
    """
    结束测试套件并输出结果
    """
    总数 = _通过数 + _失败数
    print(f"\n■ 测试完成：{_当前套件名}")
    print(f"  通过：{_通过数}/{总数}")
    if _失败数 > 0:
        print(f"  失败：{_失败数}/{总数}")
        print("  失败详情：")
        for 失败项 in _失败列表:
            print(f"    ✗ {失败项}")
    else:
        print("  全部通过！")


def 测试运行(测试函数: Callable) -> None:
    """
    运行单个测试函数

    参数:
        测试函数: 无参测试函数
    """
    try:
        测试函数()
    except Exception as e:
        global _失败数
        _失败数 += 1
        _失败列表.append(f"异常：{e}")


__all__ = [
    '断言相等', '断言不等',
    '断言为真', '断言为假',
    '断言为空', '断言不为空',
    '断言近似',
    '测试开始', '测试结束', '测试运行',
]
